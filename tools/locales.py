#!/usr/bin/env python3
"""Compile the game's translated interface labels to ordinary Ziran."""
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]

def generate():
    values = {}
    for path in sorted((ROOT / 'src/locales').glob('*.txt')):
        rows = {}
        for block in path.read_text().split('---\n'):
            lines = block.strip().splitlines()
            if lines and lines[0].startswith('[wurm_'):
                rows[lines[0][1:-1]] = '\n'.join(lines[1:])
        values[path.stem] = rows
    english = values['en']
    assert all(set(rows) == set(english) for rows in values.values()), 'Every locale must contain every key'
    header = '''// Generated by tools/locales.py from src/locales/*.txt.
#import "std/text_buffer"
#if #defined(PLATFORM_WEB) {
    #import "std/web"
} else #if !#defined(WURM_PORTABLE) {
    #import "std/c_string"
    #import "std/byte_text_linux"
    libc :: #system_library "libc";
    LocaleEnvironment :: (name: *u8) -> *u8 #foreign libc "getenv";
}
language: [3]u8;
ready: bool;
SetLanguage :: (value: string) {
    ready = true
    language = .{}
    if value.count >= 2 { language[0] = value[0]; language[1] = value[1] }
}
Detect :: () {
    if ready { return }
    ready = true
    #if #defined(PLATFORM_WEB) {
        scope := WebScope()
        bytes: [64]u8
        unused WebCopyString(WebGetObject(WebGetObject(WebGlobal, WebName("navigator")), WebName("language")), bytes[:])
        SetLanguage(TextUntilNul(bytes[:]))
        WebEnd(scope)
    } else #if !#defined(WURM_PORTABLE) {
        key: [16]u8
        unused CopyCString("LANG", key[:])
        value := LocaleEnvironment(*key[0])
        if value != null { SetLanguage(TextFromCString(value)) }
    }
}
Text :: (source: string) -> string {
    Detect()
    locale := TextUntilNul(language[:])
'''
    code = header
    for lang, rows in values.items():
        if lang == 'en':
            continue
        code += f'    if locale == {json.dumps(lang)} {{\n'
        for key, text in rows.items():
            if text != english[key]:
                code += '        if source == ' + json.dumps(english[key], ensure_ascii=False) + ' { return ' + json.dumps(text, ensure_ascii=False) + ' }\n'
        code += '    }\n'
    code += '    return source\n}\n'
    output = ROOT / 'src/localization.zi'
    if '--check' in sys.argv:
        assert output.read_text() == code, 'Run python3 tools/locales.py'
    else:
        output.write_text(code)

if __name__ == '__main__':
    generate()
