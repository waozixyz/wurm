#!/usr/bin/env python3
"""Derive the playable 20x15 mobile levels from the recovered 40x30 originals.

Each mobile cell merges a 2x2 block of original cells, so a phone screen shows
cells twice as large while every level keeps its shape: a block becomes a wall
only when three or four of its cells are solid (two-thick walls survive, thin
fringes open into floor), and a monster marker wins its block, so every
original monster survives as exactly one mobile monster. Original column 20
maps onto mobile column 10, keeping the centre entrance and exit.

The recovered archive stays the reference: this reads only the committed
assets/original/level*.dat files and writes src/levels.zi, never the archive.
"""
import argparse
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COLUMNS, ROWS = 40, 30
MOBILE_COLUMNS, MOBILE_ROWS = 20, 15


def original_grid(raw):
    return [[raw[1 + x * ROWS + y] for y in range(ROWS)] for x in range(COLUMNS)]


def is_marker(value):
    return 40 <= (value & 127) <= 45


def is_solid(value):
    if is_marker(value):
        return False
    return 20 <= value < 128


def merge_cell(grid, mx, my):
    """One mobile cell from the 2x2 block at (2*mx, 2*my): first marker wins,
    then a wall only on a 3-of-4 majority, otherwise the most common tile."""
    block = [grid[2 * mx + dx][2 * my + dy] for dx in (0, 1) for dy in (0, 1)]
    for value in block:
        if is_marker(value):
            return value
    solids = [v for v in block if is_solid(v)]
    if len(solids) >= 3:
        return Counter(solids).most_common(1)[0][0]
    passes = [v for v in block if not is_solid(v)]
    return Counter(passes).most_common(1)[0][0]


def downsample(raw):
    grid = original_grid(raw)
    mobile = [[merge_cell(grid, mx, my) for my in range(MOBILE_ROWS)]
              for mx in range(MOBILE_COLUMNS)]
    # The worm enters at column 10 and leaves the same way; a merge that
    # closed either feed cell would make the level impossible, so both are
    # held open. Count how often the guard fires as a sanity signal.
    opened = 0
    for x, y in ((10, 13), (10, 1)):
        if is_solid(mobile[x][y]):
            mobile[x][y] = 0
            opened += 1
    return mobile, opened


def generate(levels):
    mobiles = [downsample(raw) for raw in levels]
    # Printable one-byte encoding keeps generated Ziran readable and portable.
    codes = sorted({value for mobile, _ in mobiles for column in mobile for value in column})
    alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
    if len(codes) > len(alphabet):
        raise ValueError("Too many mobile tile codes")
    encode = {value: alphabet[i] for i, value in enumerate(codes)}
    lines = ["// Generated by tools/make_mobile_levels.py from assets/original. Do not hand-edit.",
             "MOBILE_LEVEL_COUNT :: 99;",
             f"MobileCodebook: [{len(codes)}]u8 = .[" + ', '.join(str(v) for v in codes) + "];",
             "MobileAlphabet :: \"" + alphabet[:len(codes)] + "\";",
             "MobileApples: [99]s32 = .[" + ", ".join(str(raw[0]) for raw in levels) + "];",
             "", "MobileLevelText :: (level: s32) -> string {"]
    for i, (mobile, _) in enumerate(mobiles, 1):
        text = ''.join(encode[mobile[x][y]] for x in range(MOBILE_COLUMNS) for y in range(MOBILE_ROWS))
        lines.append(f"    // Level {i}; column-major tile order.")
        lines.append(f'    if level == {i - 1} {{ return "{text}" }}')
    lines.extend(['    return ""', "}",
                  "", "MobileTile :: (level: s32, x: s32, y: s32) -> u8 {",
                  "    text := MobileLevelText(level)",
                  "    code := text[x * 15 + y]",
                  "    for index: 0..MobileAlphabet.count - 1 {",
                  "        if MobileAlphabet[index] == code { return MobileCodebook[index] }",
                  "    }", "    return 20", "}", ""])
    return "\n".join(lines), mobiles


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path, default=ROOT / "src/levels.zi")
    parser.add_argument("--check", action="store_true",
                        help="verify the committed file matches regeneration")
    arguments = parser.parse_args()
    levels = [(ROOT / "assets/original" / f"level{i}.dat").read_bytes() for i in range(1, 100)]
    if any(len(raw) != 1201 for raw in levels):
        raise ValueError("Incorrect original level size")
    text, mobiles = generate(levels)

    markers_before = sum(raw[1:].count(v) for raw in levels for v in range(40, 46))
    markers_before += sum(raw[1:].count(v) for raw in levels for v in range(168, 174))
    markers_after = sum(1 for mobile, _ in mobiles for column in mobile
                        for value in column if is_marker(value))
    opened = sum(opened_count for _, opened_count in mobiles)
    print(f"Mobile levels: {len(mobiles)} of {MOBILE_COLUMNS}x{MOBILE_ROWS}; "
          f"{markers_before} original markers -> {markers_after} mobile monsters; "
          f"{opened} entrance feeds held open.")

    if arguments.check:
        committed = arguments.destination.read_text()
        if committed != text:
            raise SystemExit("src/levels.zi does not match regeneration; rerun tools/make_mobile_levels.py")
        print("Mobile level source matches regeneration.")
        return
    arguments.destination.write_text(text)
    print(f"Wrote {arguments.destination}")


if __name__ == "__main__":
    main()
