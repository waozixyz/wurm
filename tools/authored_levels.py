#!/usr/bin/env python3
"""Compile explicitly published editor boards, never personal save records."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def records():
    result = []
    for path in sorted((ROOT / 'assets/authored-levels').glob('*.dat')):
        match = re.fullmatch(r'level(\d+)(-portrait)?\.dat', path.name)
        assert match and 1 <= int(match[1]) <= 200, path
        raw = path.read_bytes()
        assert len(raw) in (1201, 2401) and 1 <= raw[0] <= 12, path
        result.append((int(match[1]) - 1, bool(match[2]), raw))
    return result


def generate(check=False):
    boards = records()
    values = sorted({v for _, _, raw in boards for v in raw[1:]})
    alphabet = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'
    assert len(values) <= len(alphabet), 'authored tile codebook is full'
    codes = dict(zip(values, alphabet))
    lines = ['// Generated by tools/authored_levels.py from assets/authored-levels.',
             'AuthoredAlphabet :: "' + alphabet[:len(values)] + '";',
             f'AuthoredCodebook: [{len(values)}]u8 = .[' + ', '.join(map(str, values)) + '];', '']
    for name, first, last in (('AuthoredTiles', 1, 1201), ('AuthoredObjects', 1201, 2401)):
        lines += [name + ' :: (level: s32, portrait: bool) -> string {']
        for level, portrait, raw in boards:
            data = raw[first:last]
            if name == 'AuthoredObjects' and not any(data):
                continue
            text = ''.join(codes[v] for v in data)
            lines += [f'    if level == {level} && ' + ('' if portrait else '!') + f'portrait {{ return "{text}" }}']
        lines += ['    return ""', '}', '']
    lines += ['AuthoredApples :: (level: s32, portrait: bool) -> s32 {']
    for level, portrait, raw in boards:
        lines += [f'    if level == {level} && ' + ('' if portrait else '!') + f'portrait {{ return {raw[0]} }}']
    lines += ['    return -1', '}', '',
              'AuthoredDecode :: (code: u8) -> u8 {',
              '    for index: 0..AuthoredAlphabet.count - 1 {',
              '        if AuthoredAlphabet[index] == code { return AuthoredCodebook[index] }',
              '    }', '    return 0', '}', '']
    source = '\n'.join(lines)
    path = ROOT / 'src/authored_levels.zi'
    if check:
        assert path.read_text() == source, 'published editor boards need regeneration'
    else:
        path.write_text(source)
    print(f'{len(boards)} published editor layouts ' + ('verified.' if check else 'compiled.'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
