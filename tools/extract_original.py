#!/usr/bin/env python3
"""Recover the owner's Worm resources; never modify the supplied game.

ONLY.ONE: OO + uint32 count, then count (1024-byte complemented filename,
uint32 offset, uint32 length) records. LEVELn.DAT: apple count, followed by
40 columns of 30 bytes. PIX v2: dimensions, RLE bytes, 256 VGA RGB colors.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def archive_entries(blob):
    if blob[:2] != b"OO" or len(blob) < 6:
        raise ValueError("Not an ONLY.ONE archive")
    count = struct.unpack_from("<I", blob, 2)[0]
    end = 6 + count * 1032
    if end > len(blob):
        raise ValueError("Truncated archive directory")
    result = {}
    next_offset = end
    for i in range(count):
        at = 6 + i * 1032
        encoded = blob[at:at + 1024].split(b"\0", 1)[0]
        name = bytes(x ^ 255 for x in encoded).decode("ascii").lower()
        if not re.fullmatch(r"[a-z0-9_.]+", name) or name in result:
            raise ValueError("Unsafe or duplicate archive filename")
        offset, length = struct.unpack_from("<II", blob, at + 1024)
        if offset != next_offset or offset + length > len(blob):
            raise ValueError(f"Invalid archive range: {name}")
        result[name] = blob[offset:offset + length]
        next_offset += length
    if next_offset != len(blob):
        raise ValueError("Unaccounted archive bytes")
    return result


def decode_pix(blob):
    if blob[:5] != b"PIX\x02\x0b":
        raise ValueError("Unsupported PIX header")
    width, height, colors = struct.unpack_from("<HHH", blob, 5)
    if colors != 256 or not 0 < width * height <= 640 * 480:
        raise ValueError("Unsupported PIX dimensions/palette")
    size_bytes = 2 if width * height < 65536 else 4
    packed_size = int.from_bytes(blob[11:11 + size_bytes], "little")
    start = 11 + size_bytes
    if start + packed_size + 768 != len(blob):
        raise ValueError("Incorrect PIX stream size")
    packed = blob[start:start + packed_size]
    pixels = bytearray()
    at = 0
    while at < len(packed):
        control = packed[at]
        at += 1
        count = control & 127
        if count == 0:
            raise ValueError("Empty PIX packet")
        if control & 128:
            if at >= len(packed):
                raise ValueError("Truncated PIX run")
            pixels.extend([packed[at]] * count)
            at += 1
        else:
            if at + count > len(packed):
                raise ValueError("Truncated PIX literals")
            pixels.extend(packed[at:at + count])
            at += count
        if len(pixels) > width * height:
            raise ValueError("PIX expansion exceeds image")
    if len(pixels) != width * height:
        raise ValueError("Incomplete PIX image")
    # WURM.EXE's palette loader shifts the original 6-bit channels left by 2.
    palette = blob[-768:]
    if max(palette) > 63:
        raise ValueError("Invalid VGA palette")
    picture = Image.frombytes("P", (width, height), bytes(pixels))
    picture.putpalette([v << 2 for v in palette])
    return picture


def generate_levels(entries):
    levels = [entries[f"level{i}.dat"] for i in range(1, 100)]
    if any(len(raw) != 1201 for raw in levels):
        raise ValueError("Incorrect level size")
    # Printable one-byte encoding keeps generated Ziran readable and portable.
    codes = sorted({v for raw in levels for v in raw[1:]})
    alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!$%&()*+,-./:;<=>?@[]^_{|}~"
    if len(codes) > len(alphabet):
        raise ValueError("Too many tile codes")
    encode = {value: alphabet[i] for i, value in enumerate(codes)}
    lines = ["// Generated by tools/extract_original.py from ONLY.ONE. Do not hand-edit.",
             "ORIGINAL_LEVEL_COUNT :: 99;", f"OriginalCodebook: [{len(codes)}]u8 = .[" + ', '.join(str(v) for v in codes) + "];",
             "OriginalAlphabet :: \"" + alphabet[:len(codes)] + "\";",
             "OriginalApples: [99]s32 = .[" + ", ".join(str(raw[0]) for raw in levels) + "];",
             "", "OriginalLevelText :: (level: s32) -> string {"]
    for i, raw in enumerate(levels, 1):
        lines.append(f"    // Level {i}; original column-major tile order.")
        lines.append(f'    if level == {i - 1} {{ return "' + ''.join(encode[v] for v in raw[1:]) + '" }')
    lines.extend(['    return ""', "}",
                  "", "OriginalTile :: (level: s32, x: s32, y: s32) -> u8 {",
                  "    text := OriginalLevelText(level)",
                  "    code := text[x * 30 + y]",
                  "    for index: 0..OriginalAlphabet.count - 1 {",
                  "        if OriginalAlphabet[index] == code { return OriginalCodebook[index] }",
                  "    }", "    return 20", "}", ""])
    return "\n".join(lines), levels


def variable_length(value):
    result = [value & 127]
    value >>= 7
    while value:
        result.insert(0, (value & 127) | 128)
        value >>= 7
    return bytes(result)


def mids_to_midi(blob):
    if blob[:4] != b"RIFF" or blob[8:12] != b"MIDS":
        raise ValueError("Invalid MIDS stream")
    chunks = {}
    at = 12
    while at + 8 <= len(blob):
        size = int.from_bytes(blob[at + 4:at + 8], "little")
        chunks[blob[at:at + 4]] = blob[at + 8:at + 8 + size]
        at += 8 + size + (size & 1)
    division, _, flags = struct.unpack("<III", chunks[b"fmt "])
    if flags != 0:
        raise ValueError("Unsupported compact MIDS events")
    data = chunks[b"data"]
    count = int.from_bytes(data[:4], "little")
    at = 4
    track = bytearray()
    for _ in range(count):
        _, size = struct.unpack_from("<II", data, at)
        at += 8
        if size % 12 or at + size > len(data):
            raise ValueError("Invalid MIDS event block")
        for offset in range(at, at + size, 12):
            delta, _, event = struct.unpack_from("<III", data, offset)
            track.extend(variable_length(delta))
            kind = event >> 24
            if kind == 1:
                track.extend(b"\xff\x51\x03" + (event & 0xffffff).to_bytes(3, "big"))
            elif kind == 0:
                status = event & 255
                length = 2 if status & 0xf0 in (0xc0, 0xd0) else 3
                track.extend(event.to_bytes(4, "little")[:length])
            else:
                raise ValueError("Unsupported MIDS event")
        at += size
    if at != len(data):
        raise ValueError("Trailing MIDS data")
    track.extend(b"\x00\xff\x2f\x00")
    return b"MThd" + struct.pack(">IHHH", 6, 0, 1, division) + b"MTrk" + struct.pack(">I", len(track)) + track


def pcm_for_game(source, destination):
    subprocess.run(["ffmpeg", "-v", "error", "-nostdin", "-y", "-i", str(source),
                    "-ar", "22050", "-ac", "1", "-f", "s16le", str(destination)], check=True)


def extract(source, destination, generated):
    blob = (source / "ONLY.ONE").read_bytes()
    entries = archive_entries(blob)
    text, levels = generate_levels(entries)
    destination.mkdir(parents=True, exist_ok=True)
    manifest = {"archive_sha256": hashlib.sha256(blob).hexdigest(),
                "level_count": len(levels), "columns": 40, "rows": 30,
                "order": "column-major", "files": {}}
    for name, raw in entries.items():
        (destination / name).write_bytes(raw)
        manifest["files"][name] = {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
        if name.endswith(".pix"):
            picture = decode_pix(raw)
            picture.save(destination / (Path(name).stem + ".png"))
            rgb = picture.convert("RGBA")
            (destination / (Path(name).stem + ".argb")).write_bytes(struct.pack("<II", *rgb.size) + rgb.tobytes("raw", "BGRA"))
            if name.startswith("steine_"):
                # Color index zero is the original DirectDraw sprite color key.
                sprite = picture.convert("RGBA")
                sprite.putalpha(Image.frombytes("L", picture.size, bytes(0 if v == 0 else 255 for v in picture.tobytes())))
                sprite.save(destination / (Path(name).stem + "_sprites.png"))
                (destination / (Path(name).stem + "_sprites.argb")).write_bytes(struct.pack("<II", *sprite.size) + sprite.tobytes("raw", "BGRA"))
        elif name.endswith(".wav"):
            pcm_for_game(destination / name, destination / (Path(name).stem + ".pcm"))
    for path in sorted(source.glob("WURM*.MDS")):
        (destination / path.name.lower()).write_bytes(path.read_bytes())
        midi = destination / (path.stem.lower() + ".mid")
        midi.write_bytes(mids_to_midi(path.read_bytes()))
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    generated.parent.mkdir(parents=True, exist_ok=True)
    generated.write_text(text)
    print(f"Recovered {len(levels)} levels, 14 images, 4 sounds and 3 MIDI streams.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--destination", type=Path, default=ROOT / "assets/original")
    parser.add_argument("--generated", type=Path, default=ROOT / "src/original_levels.zi")
    args = parser.parse_args()
    extract(args.source, args.destination, args.generated)
